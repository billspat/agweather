        <h2>Biography</h2>
        <p>
Jeff Andresen is Professor of meteorology/climatology with Michigan State University’s Department of Geography, Environment, and Spatial Sciences, Extension Specialist with Michigan State University Extension, and the State Climatologist for Michigan. He holds a B.S. degree from Northern Illinois University in meteorology and M.S. and Ph.D. degrees from Purdue University in agricultural meteorology/climatology. Dr. Andresen has previous professional experience with the National Weather Service and with the USDA's World Agricultural Outlook Board in Washington, D.C., where he was involved in international crop/weather impact assessment and production estimation. He currently serves as director of Michigan’s Enviroweather information system which supports agricultural pest and production management related decision-making across the state (https://enviroweather.msu.edu), as co-director of the Great Lakes Regional Science Assessment Center, one of 12 NOAA Climate Adaptation Partner teams that help the nation prepare for and adapt to climate variability and change, and as an extension specialist maintaining an active outreach program including dissemination of weather and climate data and related information to the general public and continuing education activities.
